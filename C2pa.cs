namespace Atelier;

/// <summary>
/// Reads the Content Credentials (C2PA) a picture carries, for the metadata pane.
///
/// A C2PA manifest store is a JUMBF box tree tucked into the file: APP11 segments in a
/// JPEG, a caBX chunk in a PNG, a C2PA chunk in a WebP, a uuid box in HEIF/AVIF, or a
/// .c2pa file beside the picture. Inside, each manifest holds a CBOR claim (which app
/// made it), its assertions (what was done: created, edited, generated by AI) and a
/// COSE signature whose certificate names who signed it.
///
/// This is a reader, not a validator. Nothing here checks the signature or the hashes
/// that bind the manifest to the pixels, so the pane says so; what it shows is what the
/// file claims, which is what people want to see first -- and an honest "unverified"
/// beats pulling in a full trust-list implementation for a viewer.
/// </summary>
public static class C2pa
{
    /// <summary>One labelled line for the metadata pane.</summary>
    public readonly record struct Field(string Label, string Value);

    /// <summary>The C2PA UUID that marks a uuid box as a manifest store in ISO BMFF files.</summary>
    private static readonly byte[] BmffUuid =
        { 0xD8, 0xFE, 0xC3, 0xD6, 0x1B, 0x0E, 0x48, 0x3C, 0x92, 0x97, 0x58, 0x28, 0x87, 0x7E, 0xC4, 0x81 };

    /// <summary>
    /// The credentials in <paramref name="path"/>, or null if it carries none. A store
    /// that is present but unreadable comes back as a single line saying so, rather
    /// than as null -- "there is something here" is worth knowing on its own.
    /// </summary>
    public static List<Field>? Read(string path)
    {
        byte[]? store;
        string where = "Embedded in the file";
        try
        {
            store = FindStore(path);
            if (store == null)
            {
                string sidecar = Path.ChangeExtension(path, ".c2pa");
                if (File.Exists(sidecar))
                {
                    store = File.ReadAllBytes(sidecar);
                    where = $"Sidecar file ({Path.GetFileName(sidecar)})";
                }
            }
        }
        catch
        {
            return null;
        }
        if (store == null) return RemoteReference(path);

        try
        {
            return Describe(store, where);
        }
        catch
        {
            return new List<Field>
            {
                new("Status", "Present, but could not be read"),
                new("Stored", where),
            };
        }
    }

    /// <summary>
    /// A manifest kept on a server rather than in the file is pointed at from XMP, by
    /// dcterms:provenance. It is not fetched -- opening a picture should not phone home --
    /// but the pointer is worth showing.
    /// </summary>
    private static List<Field>? RemoteReference(string path)
    {
        try
        {
            foreach (var xmp in MetadataExtractor.ImageMetadataReader.ReadMetadata(path)
                         .OfType<MetadataExtractor.Formats.Xmp.XmpDirectory>())
            {
                string? url = xmp.XmpMeta?.GetPropertyString("http://purl.org/dc/terms/", "provenance");
                if (string.IsNullOrWhiteSpace(url)) continue;
                // "self#jumbf=..." points into the file itself: the store was there once
                // and something has since removed it.
                if (url.StartsWith("self#", StringComparison.Ordinal))
                    return new List<Field> { new("Status", "Referenced, but missing from the file") };
                return new List<Field>
                {
                    new("Status", "Stored remotely; not downloaded"),
                    new("Manifest URL", url),
                };
            }
        }
        catch { }
        return null;
    }

    /// <summary>True if the file carries an embedded manifest store. Never throws.</summary>
    public static bool IsPresent(string path)
    {
        try { return FindStore(path) != null; }
        catch { return false; }
    }

    // ---- Finding the store in each container -------------------------------------

    internal static byte[]? FindStore(string path)
    {
        byte[] data = File.ReadAllBytes(path);
        if (data.Length < 12) return null;

        if (data[0] == 0xFF && data[1] == 0xD8) return FromJpeg(data);
        if (data.AsSpan(0, 8).SequenceEqual(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A }))
            return FromPng(data);
        if (Ascii(data, 0, 4) == "RIFF" && Ascii(data, 8, 4) == "WEBP") return FromWebP(data);
        if (Ascii(data, 4, 4) == "ftyp") return FromBmff(data);
        return null;
    }

    /// <summary>
    /// JPEG splits the store across APP11 segments, each starting "JP", a box instance
    /// number and a sequence number. Every segment after the first repeats the box's
    /// LBox/TBox header, which has to be dropped before the pieces are joined.
    /// </summary>
    private static byte[]? FromJpeg(byte[] data)
    {
        var parts = new SortedDictionary<int, (List<(uint Seq, byte[] Bytes)> Pieces, int HeaderLength)>();
        int pos = 2;
        while (pos + 4 <= data.Length && data[pos] == 0xFF)
        {
            byte marker = data[pos + 1];
            if (marker == 0xD8 || (marker >= 0xD0 && marker <= 0xD7) || marker == 0x01) { pos += 2; continue; }
            if (marker == 0xFF) { pos++; continue; }
            if (marker == 0xDA || marker == 0xD9) break;

            int length = (data[pos + 2] << 8) | data[pos + 3];
            int start = pos + 4, end = pos + 2 + length;
            if (end > data.Length || length < 2) break;

            if (marker == 0xEB && end - start > 16 && data[start] == 'J' && data[start + 1] == 'P')
            {
                int instance = (data[start + 2] << 8) | data[start + 3];
                uint seq = ReadU32(data, start + 4);
                int box = start + 8;
                int header = ReadU32(data, box) == 1 ? 16 : 8;
                if (!parts.TryGetValue(instance, out var entry))
                    entry = (new List<(uint, byte[])>(), header);
                entry.Pieces.Add((seq, data[box..end]));
                parts[instance] = entry;
            }
            pos = end;
        }

        foreach (var (_, entry) in parts)
        {
            var ordered = entry.Pieces.OrderBy(p => p.Seq).ToList();
            using var joined = new MemoryStream();
            for (int i = 0; i < ordered.Count; i++)
            {
                var bytes = ordered[i].Bytes;
                if (i == 0) joined.Write(bytes);
                else if (bytes.Length > entry.HeaderLength) joined.Write(bytes, entry.HeaderLength, bytes.Length - entry.HeaderLength);
            }
            var store = joined.ToArray();
            if (IsManifestStore(store)) return store;
        }
        return null;
    }

    private static byte[]? FromPng(byte[] data)
    {
        int pos = 8;
        while (pos + 12 <= data.Length)
        {
            int length = (int)ReadU32(data, pos);
            string type = Ascii(data, pos + 4, 4);
            if (length < 0 || pos + 12 + length > data.Length) break;
            if (type == "caBX") return data[(pos + 8)..(pos + 8 + length)];
            if (type == "IEND") break;
            pos += 12 + length;
        }
        return null;
    }

    private static byte[]? FromWebP(byte[] data)
    {
        int pos = 12;
        while (pos + 8 <= data.Length)
        {
            string type = Ascii(data, pos, 4);
            int length = (int)ReadU32LE(data, pos + 4);
            if (length < 0 || pos + 8 + length > data.Length) break;
            if (type == "C2PA") return data[(pos + 8)..(pos + 8 + length)];
            pos += 8 + length + (length & 1);
        }
        return null;
    }

    /// <summary>
    /// HEIF and AVIF: a top-level uuid box with the C2PA UUID, a version/flags word, a
    /// purpose string ("manifest" adds an 8-byte offset after it), then the store.
    /// </summary>
    private static byte[]? FromBmff(byte[] data)
    {
        long pos = 0;
        while (pos + 8 <= data.Length)
        {
            long size = ReadU32(data, (int)pos);
            string type = Ascii(data, (int)pos + 4, 4);
            int header = 8;
            if (size == 1) { size = (long)ReadU64(data, (int)pos + 8); header = 16; }
            else if (size == 0) size = data.Length - pos;
            if (size < header || pos + size > data.Length) break;

            if (type == "uuid" && size >= header + 20 &&
                data.AsSpan((int)pos + header, 16).SequenceEqual(BmffUuid))
            {
                int p = (int)pos + header + 16 + 4;
                int end = (int)(pos + size);
                int nul = Array.IndexOf(data, (byte)0, p, end - p);
                if (nul < 0) return null;
                string purpose = Encoding.ASCII.GetString(data, p, nul - p);
                p = nul + 1;
                if (purpose == "manifest") p += 8;
                if (p < end && purpose is "manifest" or "original") return data[p..end];
            }
            pos += size;
        }
        return null;
    }

    // ---- JUMBF -------------------------------------------------------------------

    /// <summary>A JUMBF superbox: its label and the boxes it holds.</summary>
    private sealed class Jumb
    {
        public string Label = "";
        public readonly List<(string Type, byte[] Payload)> Content = new();
        public readonly List<Jumb> Children = new();

        public Jumb? Child(string label) => Children.FirstOrDefault(c => c.Label == label);

        public byte[]? First(string type) => Content.FirstOrDefault(c => c.Type == type).Payload;
    }

    private static bool IsManifestStore(byte[] store)
    {
        try { return ParseBox(store, 0, store.Length)?.Label == "c2pa"; }
        catch { return false; }
    }

    /// <summary>Parses the jumb box at <paramref name="start"/>, or null if it is not one.</summary>
    private static Jumb? ParseBox(byte[] data, int start, int limit)
    {
        var (type, payloadStart, end) = BoxAt(data, start, limit);
        if (type != "jumb") return null;

        var jumb = new Jumb();
        int pos = payloadStart;
        bool first = true;
        while (pos + 8 <= end)
        {
            var (childType, childStart, childEnd) = BoxAt(data, pos, end);
            if (first && childType == "jumd")
            {
                jumb.Label = ReadLabel(data, childStart, childEnd);
            }
            else if (childType == "jumb")
            {
                var child = ParseBox(data, pos, end);
                if (child != null) jumb.Children.Add(child);
            }
            else
            {
                jumb.Content.Add((childType, data[childStart..childEnd]));
            }
            first = false;
            pos = childEnd;
        }
        return jumb;
    }

    private static (string Type, int PayloadStart, int End) BoxAt(byte[] data, int start, int limit)
    {
        long length = ReadU32(data, start);
        string type = Ascii(data, start + 4, 4);
        int header = 8;
        if (length == 1) { length = (long)ReadU64(data, start + 8); header = 16; }
        else if (length == 0) length = limit - start;
        if (length < header || start + length > limit) throw new InvalidDataException("Bad JUMBF box");
        return (type, start + header, (int)(start + length));
    }

    /// <summary>A description box: 16-byte type, a toggles byte, then the label if bit 1 is set.</summary>
    private static string ReadLabel(byte[] data, int start, int end)
    {
        int p = start + 16;
        if (p >= end || (data[p] & 0x02) == 0) return "";
        p++;
        int nul = Array.IndexOf(data, (byte)0, p, end - p);
        return Encoding.UTF8.GetString(data, p, (nul < 0 ? end : nul) - p);
    }

    // ---- Turning the store into lines ----------------------------------------------

    private static List<Field> Describe(byte[] storeBytes, string where)
    {
        var store = ParseBox(storeBytes, 0, storeBytes.Length) ?? throw new InvalidDataException("Not a manifest store");
        if (store.Children.Count == 0) throw new InvalidDataException("Empty manifest store");

        // The active manifest is the last one; the earlier ones belong to ingredients.
        var manifest = store.Children[^1];
        var fields = new List<Field>();

        var claimBox = manifest.Child("c2pa.claim.v2") ?? manifest.Child("c2pa.claim");
        var claim = claimBox?.First("cbor") is { } claimBytes ? Cbor(claimBytes) as Dictionary<string, object?> : null;

        var signature = manifest.Child("c2pa.signature")?.First("cbor");
        if (signature != null) DescribeSignature(signature, fields);

        if (claim != null)
        {
            if (Generator(claim) is { } app) fields.Add(new("App or device used", app));
            if (Text(claim, "dc:title") is { } title) fields.Add(new("Title", title));
            if (Text(claim, "dc:format") is { } format) fields.Add(new("Claimed format", format));
        }

        var assertions = manifest.Child("c2pa.assertions");
        if (assertions != null) DescribeAssertions(assertions, fields);

        if (store.Children.Count > 1) fields.Add(new("Manifests", store.Children.Count.ToString()));
        fields.Add(new("Manifest", manifest.Label));
        fields.Add(new("Stored", where));
        return fields;
    }

    private static void DescribeSignature(byte[] cose, List<Field> fields)
    {
        // COSE_Sign1: [protected (bstr), unprotected (map), payload, signature].
        if (Cbor(cose) is not List<object?> { Count: >= 2 } parts) return;
        var headers = new Dictionary<string, object?>();
        if (parts[0] is byte[] protectedBytes && protectedBytes.Length > 0 &&
            Cbor(protectedBytes) is Dictionary<string, object?> prot)
            foreach (var (k, v) in prot) headers[k] = v;
        if (parts[1] is Dictionary<string, object?> unprot)
            foreach (var (k, v) in unprot) headers.TryAdd(k, v);

        // 33 is x5chain: the signing certificate first, as one bstr or an array of them.
        // Manifests from before C2PA 1.0 spelled the label out instead.
        var chain = headers.GetValueOrDefault("33") ?? headers.GetValueOrDefault("x5chain");
        byte[]? leaf = chain as byte[] ?? (chain as List<object?>)?.FirstOrDefault() as byte[];
        if (leaf != null)
        {
            try
            {
                using var cert = new X509Certificate2(leaf);
                fields.Add(new("Issued by", NamePart(cert.SubjectName, "O") ?? NamePart(cert.SubjectName, "CN") ?? cert.Subject));
                if ((NamePart(cert.IssuerName, "O") ?? NamePart(cert.IssuerName, "CN")) is { } ca)
                    fields.Add(new("Certificate issuer", ca));
            }
            catch { }
        }

        if (SigningTime(headers) is { } when) fields.Add(new("Signed on", when.ToLocalTime().ToString("g")));

        if (headers.GetValueOrDefault("1") is long alg) fields.Add(new("Signature algorithm", Algorithm(alg)));
        fields.Add(new("Signature", "Not verified by Atelier"));
    }

    /// <summary>The RFC 3161 timestamp in sigTst or sigTst2, if the signer asked for one.</summary>
    private static DateTimeOffset? SigningTime(Dictionary<string, object?> headers)
    {
        foreach (var key in new[] { "sigTst2", "sigTst" })
        {
            if (headers.GetValueOrDefault(key) is not Dictionary<string, object?> tst) continue;
            if (tst.GetValueOrDefault("tstTokens") is not List<object?> tokens) continue;
            foreach (var token in tokens.OfType<Dictionary<string, object?>>())
            {
                if (token.GetValueOrDefault("val") is byte[] der &&
                    Rfc3161TimestampToken.TryDecode(der, out var decoded, out _))
                    return decoded!.TokenInfo.Timestamp;
            }
        }
        return null;
    }

    private static void DescribeAssertions(Jumb assertions, List<Field> fields)
    {
        var actions = new List<string>();
        var sources = new HashSet<string>();
        var ingredients = new List<string>();
        var authors = new List<string>();

        foreach (var assertion in assertions.Children)
        {
            string label = assertion.Label;
            // Repeated assertions carry an instance suffix: c2pa.ingredient__1.
            int instance = label.IndexOf("__", StringComparison.Ordinal);
            string kind = instance >= 0 ? label[..instance] : label;

            if (kind is "c2pa.actions" or "c2pa.actions.v2" && Body(assertion) is Dictionary<string, object?> body &&
                body.GetValueOrDefault("actions") is List<object?> list)
            {
                foreach (var action in list.OfType<Dictionary<string, object?>>())
                {
                    string name = Humanise(Text(action, "action") ?? "unknown");
                    string? agent = Agent(action.GetValueOrDefault("softwareAgent"));
                    string line = agent != null ? $"{name} with {agent}" : name;
                    if (!actions.Contains(line)) actions.Add(line);
                    if (Text(action, "digitalSourceType") is { } source) sources.Add(source);
                }
            }
            else if (kind.StartsWith("c2pa.ingredient", StringComparison.Ordinal) &&
                     Body(assertion) is Dictionary<string, object?> ingredient)
            {
                string title = Text(ingredient, "dc:title") ?? "Untitled";
                string? relation = Text(ingredient, "relationship");
                ingredients.Add(relation == "parentOf" ? $"{title} (edited from)" : title);
            }
            else if (kind is "stds.schema-org.CreativeWork" && Body(assertion) is Dictionary<string, object?> work)
            {
                var author = work.GetValueOrDefault("author");
                foreach (var person in author as List<object?> ?? new List<object?> { author })
                {
                    if (person is Dictionary<string, object?> p && Text(p, "name") is { } who) authors.Add(who);
                    else if (person is string s) authors.Add(s);
                }
            }
        }

        string? ai = sources.Select(DescribeSource).FirstOrDefault(s => s != null);
        if (ai != null) fields.Add(new("Made with", ai));
        if (actions.Count > 0) fields.Add(new("Actions", string.Join("\n", actions)));
        if (authors.Count > 0) fields.Add(new("Author", string.Join(", ", authors.Distinct())));
        if (ingredients.Count > 0) fields.Add(new("Ingredients", string.Join("\n", ingredients)));
    }

    /// <summary>An assertion's payload, whichever of CBOR or JSON it was written in.</summary>
    private static object? Body(Jumb assertion)
    {
        if (assertion.First("cbor") is { } cbor) return Cbor(cbor);
        if (assertion.First("json") is { } json) return Json(JsonDocument.Parse(json).RootElement);
        return null;
    }

    /// <summary>
    /// The IPTC digital source types people actually care about -- above all, whether
    /// the picture came out of a generative model. Anything else is left unsaid.
    /// </summary>
    private static string? DescribeSource(string uri) => uri[(uri.LastIndexOf('/') + 1)..] switch
    {
        "trainedAlgorithmicMedia" => "Generative AI",
        "compositeWithTrainedAlgorithmicMedia" => "Generative AI (edited or combined)",
        "algorithmicallyEnhanced" => "AI enhancement",
        "algorithmicMedia" => "Algorithmic (non-AI) generation",
        "compositeSynthetic" => "Composite of synthetic elements",
        "digitalCapture" => "Camera capture",
        "computationalCapture" => "Computational camera capture",
        "negativeFilm" or "positiveFilm" or "print" => "Scan of a physical original",
        "digitalArt" => "Digital art",
        "screenCapture" => "Screen capture",
        _ => null,
    };

    private static string? Generator(Dictionary<string, object?> claim)
    {
        // v2 claims carry one map; v1 claims an array of them plus a free-text string.
        var info = claim.GetValueOrDefault("claim_generator_info");
        var first = info as Dictionary<string, object?> ?? (info as List<object?>)?.FirstOrDefault() as Dictionary<string, object?>;
        if (first != null && Text(first, "name") is { } name)
            return Text(first, "version") is { } version ? $"{name} {version}" : name;
        return Text(claim, "claim_generator")?.Split(' ')[0].Replace('/', ' ');
    }

    private static string? Agent(object? agent) => agent switch
    {
        string s => s,
        Dictionary<string, object?> map when Text(map, "name") is { } name =>
            Text(map, "version") is { } version ? $"{name} {version}" : name,
        _ => null,
    };

    /// <summary>"c2pa.color_adjustments" to "Color adjustments".</summary>
    private static string Humanise(string action)
    {
        string bare = action.StartsWith("c2pa.", StringComparison.Ordinal) ? action[5..] : action;
        bare = bare.Replace('_', ' ').Replace('.', ' ');
        return bare.Length == 0 ? action : char.ToUpperInvariant(bare[0]) + bare[1..];
    }

    private static string Algorithm(long alg) => alg switch
    {
        -7 => "ES256",
        -35 => "ES384",
        -36 => "ES512",
        -37 => "PS256",
        -38 => "PS384",
        -39 => "PS512",
        -8 => "Ed25519",
        _ => alg.ToString(),
    };

    private static string? NamePart(X500DistinguishedName name, string key)
    {
        foreach (var part in name.EnumerateRelativeDistinguishedNames())
        {
            if (part.GetSingleElementType().FriendlyName == key)
                return part.GetSingleElementValue();
        }
        return null;
    }

    private static string? Text(Dictionary<string, object?> map, string key) =>
        map.GetValueOrDefault(key) is string s && s.Length > 0 ? s : null;

    // ---- CBOR and JSON into plain objects --------------------------------------------

    /// <summary>
    /// Decodes CBOR into maps (string keys -- integer COSE labels become "1", "33"),
    /// lists, strings, longs, byte arrays and bools. Tags are looked through.
    /// </summary>
    internal static object? Cbor(byte[] bytes)
    {
        var reader = new CborReader(bytes, CborConformanceMode.Lax, allowMultipleRootLevelValues: true);
        return CborValue(reader);
    }

    private static object? CborValue(CborReader reader)
    {
        switch (reader.PeekState())
        {
            case CborReaderState.Tag:
                reader.ReadTag();
                return CborValue(reader);
            case CborReaderState.StartMap:
            {
                var map = new Dictionary<string, object?>();
                reader.ReadStartMap();
                while (reader.PeekState() != CborReaderState.EndMap)
                {
                    string key = CborValue(reader)?.ToString() ?? "";
                    map[key] = CborValue(reader);
                }
                reader.ReadEndMap();
                return map;
            }
            case CborReaderState.StartArray:
            {
                var list = new List<object?>();
                reader.ReadStartArray();
                while (reader.PeekState() != CborReaderState.EndArray) list.Add(CborValue(reader));
                reader.ReadEndArray();
                return list;
            }
            case CborReaderState.TextString:
            case CborReaderState.StartIndefiniteLengthTextString:
                return reader.ReadTextString();
            case CborReaderState.ByteString:
            case CborReaderState.StartIndefiniteLengthByteString:
                return reader.ReadByteString();
            case CborReaderState.UnsignedInteger:
            case CborReaderState.NegativeInteger:
                return reader.ReadInt64();
            case CborReaderState.Boolean:
                return reader.ReadBoolean();
            case CborReaderState.HalfPrecisionFloat:
            case CborReaderState.SinglePrecisionFloat:
            case CborReaderState.DoublePrecisionFloat:
                return reader.ReadDouble();
            default:
                reader.SkipValue();
                return null;
        }
    }

    private static object? Json(JsonElement e) => e.ValueKind switch
    {
        JsonValueKind.Object => e.EnumerateObject().ToDictionary(p => p.Name, p => Json(p.Value)),
        JsonValueKind.Array => e.EnumerateArray().Select(Json).ToList(),
        JsonValueKind.String => e.GetString(),
        JsonValueKind.Number => e.TryGetInt64(out long l) ? l : e.GetDouble(),
        JsonValueKind.True => true,
        JsonValueKind.False => false,
        _ => null,
    };

    // ---- Byte helpers ----------------------------------------------------------------

    private static string Ascii(byte[] data, int start, int length) =>
        start + length <= data.Length ? Encoding.ASCII.GetString(data, start, length) : "";

    private static uint ReadU32(byte[] d, int p) =>
        (uint)(d[p] << 24 | d[p + 1] << 16 | d[p + 2] << 8 | d[p + 3]);

    private static ulong ReadU64(byte[] d, int p) => (ulong)ReadU32(d, p) << 32 | ReadU32(d, p + 4);

    private static uint ReadU32LE(byte[] d, int p) =>
        (uint)(d[p] | d[p + 1] << 8 | d[p + 2] << 16 | d[p + 3] << 24);
}
